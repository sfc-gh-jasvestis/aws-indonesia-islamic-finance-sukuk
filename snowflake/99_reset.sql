ALTER TASK IF EXISTS APP.TASK_REVALUE_PORTFOLIO SUSPEND;
ALTER TASK IF EXISTS APP.TASK_FORECAST_YIELDS SUSPEND;

-- Force refresh Dynamic Tables
ALTER DYNAMIC TABLE CURATED.PORTFOLIO_SUMMARY REFRESH;
ALTER DYNAMIC TABLE CURATED.YIELD_CURVES REFRESH;
ALTER DYNAMIC TABLE CURATED.ISSUER_RISK REFRESH;
ALTER DYNAMIC TABLE CURATED.MATURITY_LADDER REFRESH;

