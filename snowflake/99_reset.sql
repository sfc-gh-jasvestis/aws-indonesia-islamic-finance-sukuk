-- SELECT COUNT(*) FROM ISLAMIC_SUKUK_INDONESIA.RAW.VALUATIONS → 20000
-- SELECT COUNT(*) FROM ISLAMIC_SUKUK_INDONESIA.RAW.MARKET_DATA → 80000

-- Resume tasks
ALTER TASK IF EXISTS APP.TASK_FORECAST_YIELDS RESUME;
ALTER TASK IF EXISTS APP.TASK_REVALUE_PORTFOLIO RESUME;
ALTER TASK IF EXISTS APP.TASK_INGEST_MARKET_DATA RESUME;
